    /// seam B: upstream connection breaks mid-stream (no `[DONE]`) → the client sees a truncated stream after the
    /// already-sent frames pass through as-is (headers already sent, status stays 200); the usecase writes a 502
    /// failure log and has billed the incremental usage. Only this seam reliably covers mid-stream interruption and termination (Spec §Testing Decisions).
    #[tokio::test]
    async fn chat_completions_streaming_interruption_truncates_and_bills_partial_usage() {
        let h = harness().await;

        // Mock upstream: emits delta frames + a usage frame, then injects an error mid-stream (connection reset, no [DONE]).
        // A short sleep after each frame: ensure the gateway has received the response headers and opened the stream,
        // and frames were reliably read before the disconnect (RST drops in-flight bytes, so the error must lag the last frame).
        let frame_delta = "data: {\"id\":\"chatcmpl-1\",\"object\":\"chat.completion.chunk\",\"choices\":[{\"index\":0,\"delta\":{\"content\":\"Hello\"}}]}\n\n";
        let frame_usage = "data: {\"id\":\"chatcmpl-1\",\"object\":\"chat.completion.chunk\",\"choices\":[{\"index\":0,\"delta\":{},\"finish_reason\":\"stop\"}],\"usage\":{\"prompt_tokens\":3,\"completion_tokens\":2,\"total_tokens\":5}}\n\n";
        let upstream = Router::new().route(
            "/chat/completions",
            post(move || async move {
                (
                    StatusCode::OK,
                    [(header::CONTENT_TYPE, "text/event-stream")],
                    Body::from_stream(futures_util::stream::unfold(0u8, move |step| async move {
                        match step {
                            0 => Some((
                                Ok::<_, std::io::Error>(Bytes::from_static(frame_delta.as_bytes())),
                                1,
                            )),
                            1 => {
                                tokio::time::sleep(std::time::Duration::from_millis(50)).await;
                                Some((
                                    Ok::<_, std::io::Error>(Bytes::from_static(
                                        frame_usage.as_bytes(),
                                    )),
                                    2,
                                ))
                            }
                            2 => {
                                tokio::time::sleep(std::time::Duration::from_millis(50)).await;
                                Some((
                                    Err::<_, std::io::Error>(std::io::Error::other(
                                        "upstream connection reset",
                                    )),
                                    3,
                                ))
                            }
                            _ => None,
                        }
                    })),
                )
            }),
        );
        let (base, handle) = test_util::spawn(upstream).await;

        let key = seed_channel_and_key(&h, &base).await;
        let app = app(&h);

        let response = app
            .oneshot(post_chat(
                r#"{"model":"gpt-4o","stream":true,"messages":[{"role":"user","content":"hi"}]}"#,
                Some(&key),
                "trace-stream-err",
            ))
            .await
            .expect("oneshot");

        assert_eq!(
            response.status(),
            StatusCode::OK,
            "响应头已发出，流中断无法改为 502"
        );
        assert_eq!(
            response
                .headers()
                .get(header::CONTENT_TYPE)
                .map(|v| v.to_str().unwrap()),
            Some("text/event-stream"),
            "SSE 响应应带 text/event-stream"
        );

        let body = axum::body::to_bytes(response.into_body(), usize::MAX)
            .await
            .expect("read body");
        handle.abort();
        let text = String::from_utf8_lossy(&body);
        assert_eq!(
            text,
            format!("{frame_delta}{frame_usage}"),
            "已下发的帧原样透传后截断；实际：{text}"
        );
        assert!(
            !text.contains("[DONE]"),
            "流中断：客户端不应看到 [DONE] 收尾；实际：{text}"
        );

        // Usecase side: 502 failure log (with incremental usage) + billing from the incremental usage.
        let row = sqlx::query(
            "SELECT trace_id, status_code, is_stream, total_tokens, error_message FROM request_logs",
        )
        .fetch_one(&h.pool)
        .await
        .expect("request_log row");
        assert_eq!(row.get::<String, _>(0), "trace-stream-err");
        assert_eq!(
            row.get::<i64, _>(1),
            502,
            "流中断写失败日志（与线上 200 分离）"
        );
        assert_eq!(row.get::<i64, _>(2), 1, "is_stream 应标记为真");
        assert_eq!(row.get::<i64, _>(3), 5, "失败日志携带已聚合的增量 usage");
        assert!(
            row.get::<Option<String>, _>(4).is_some(),
            "流中断应记录失败原因"
        );

        let saved = h
            .api_key_repo
            .find_by_key(&key)
            .await
            .expect("find")
            .expect("found");
        assert_eq!(
            saved.quota.used, 5,
            "流中断时已下发的增量 usage 同样累加配额"
        );
    }

