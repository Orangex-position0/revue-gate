/// Trace id propagated through a request: written to request extensions by the middleware, shared by handlers / spans / log persistence.
#[derive(Debug, Clone)]
pub struct TraceId(pub String);

/// Client-injectable request ID header (echoed back when present, generated by the middleware otherwise). The http crate does not predefine this header name.
static X_REQUEST_ID: HeaderName = HeaderName::from_static("x-request-id");

/// Generate/reuse a trace id and propagate it through the request (outermost middleware, runs before the TraceLayer span is created).
pub(crate) async fn trace_id_middleware(mut request: Request, next: Next) -> Response {
    let trace_id = request
        .headers()
        .get(&X_REQUEST_ID)
        .and_then(|v| v.to_str().ok())
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(str::to_string)
        .unwrap_or_else(|| Uuid::now_v7().to_string());
    request.extensions_mut().insert(TraceId(trace_id.clone()));
    let mut response = next.run(request).await;
    if let Ok(value) = HeaderValue::from_str(&trace_id) {
        response.headers_mut().insert(&X_REQUEST_ID, value);
    }
    response
}

/// TraceLayer span builder: reads the TraceId extension written by the middleware and carries it into the span fields.
#[derive(Clone)]
pub struct TraceIdSpan;

impl<B> MakeSpan<B> for TraceIdSpan {
    fn make_span(&mut self, request: &axum::http::Request<B>) -> Span {
        let trace_id = request
            .extensions()
            .get::<TraceId>()
            .map(|t| t.0.as_str())
            .unwrap_or("unknown");
        tracing::info_span!(
            "request",
            method = %request.method(),
            uri = %request.uri(),
            trace_id = %trace_id
        )
    }
}

/// Emit structured logs (status code + latency) inside the request span after the response completes.
#[derive(Clone)]
pub struct TraceOnResponse;

impl<B> OnResponse<B> for TraceOnResponse {
    fn on_response(self, response: &axum::http::Response<B>, latency: Duration, span: &Span) {
        span.in_scope(|| {
            tracing::debug!(
                status = response.status().as_u16(),
                latency_ms = latency.as_millis() as u64,
                "finished processing request"
            );
        });
    }
}

