//! Data plane: /v1/* request handlers + trace id propagation middleware (see docs/Architecture-backend.md).
//!
//! Responsibility layering:
//! - `trace_id_middleware` (outermost): reads/generates `x-request-id` → stores it in request extensions,
//!   echoes it back in the response header so clients can correlate the trace;
//! - `TraceIdSpan` / `TraceOnResponse`: the TraceLayer span carries trace_id and emits structured logs after the response;
//! - `chat_completions` / `models`: parse the request → call the proxy / model-list usecases → map errors to HTTP status codes.
//!
//! Streaming requests (`stream: true`) go through SSE passthrough: the event stream returned by the proxy
//! usecase is written frame by frame to the response body (`text/event-stream`); `[DONE]` is passed through
//! from upstream or synthesized by a conversion adapter, and the response ends when the stream ends; billing
//! and logging complete inline in the usecase when the stream ends.
//! Upstream keys are never returned: upstream error bodies are converged by the adapter into a generic error body (red line, see providers.rs).

